"""Builds legends.js: a 0-100 'legend' score per act (reputation, independent of how the act is scheduled).

Source: Spotify play counts via the desktop app's spotify_cli (the app must be running and logged in).
For each act: search up to 20 tracks of the artist, keep the ones credited to the exact artist name, and add up
their total_plays. The search is not ranked by popularity, so this is a sample of the catalogue, not the full total.
Score = log scale of that sum: 100,000 plays = 0, 1 billion plays = 100 (so 10 million = 50).
Collaborations ("A & B", "A with B") take the best score of the parts; acts without a match on Spotify get no score.
Results are cached in %TEMP%/lgw_spotify.json, so re-runs are cheap.
Run: uv run python tools/build_legends.py
"""
import json, math, os, re, subprocess, unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(os.environ.get("TEMP", "/tmp"), "lgw_spotify.json")
CLI = os.environ.get("SPOTIFY_CLI_PATH") or os.path.join(os.environ.get("APPDATA", ""), "Spotify", "spotify_cli.exe")

SPLIT = re.compile(r"\s+(?:&|\+|x|feat\.?|ft\.?|ft|with|presents?|performing|performs|plays|meets|live mixed by|live processing by|b2b)\s+|\s+by\s+|,\s*|:\s+", re.I)


def norm(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", "", s)


def segments(name):
    name = re.sub(r"^(curator|artist in residence|expo):\s*", "", name, flags=re.I)
    name = re.sub(r"\(.*?\)|[‘’'\"“”]", "", name)
    name = re.split(r"\s+(?:presents?|performing|performs|plays|by)\s+", name, maxsplit=1, flags=re.I)[0]  # what follows is a project or work, not the act
    return [p.strip() for p in SPLIT.split(name) if len(p.strip()) > 2]


def cli(*args):
    r = subprocess.run([CLI, *args, "--format", "json"], capture_output=True, text=True, encoding="utf8", timeout=120)
    if r.returncode != 0:
        raise RuntimeError(r.stdout.strip() or r.stderr.strip())
    return json.loads(r.stdout)


def plays(seg):
    """{tracks, plays}: number of matching tracks found and the sum of their total_plays"""
    q = seg.replace('"', "").replace("\\", "")
    res = cli("search", f'artist:"{q}"', "--type", "track", "--limit", "20")
    k = norm(seg)
    uris = [t["uri"] for t in res.get("tracks", []) if any(norm(a) == k for a in t.get("artists", []))]
    if not uris:
        return {"tracks": 0, "plays": 0}
    total = 0
    for e in cli("lookup", *uris, "--fields", "total_plays").get("entities", []):
        total += int(float(next((m["value"] for m in e.get("metadata", []) if m["field"] == "total_plays"), 0) or 0))
    return {"tracks": len(uris), "plays": total}


def main():
    src = open(os.path.join(ROOT, "lineups.js"), encoding="utf8").read()
    names = sorted(set(json.loads(m.group(1)) for m in re.finditer(r'"n":("(?:[^"\\]|\\.)*")', src)))
    cache = json.load(open(CACHE, encoding="utf8")) if os.path.exists(CACHE) else {}
    segs = sorted({s for n in names for s in segments(n)})
    todo = [s for s in segs if s not in cache]
    print(len(names), "acts,", len(segs), "segments,", len(todo), "to look up on Spotify (resumable; Ctrl+C is safe)", flush=True)
    try:
        for i, s in enumerate(todo):
            try:
                cache[s] = plays(s)
            except RuntimeError as e:  # e.g. Spotify not running: leave uncached, next run retries
                print("  failed", s, e)
            if i % 25 == 0:
                json.dump(cache, open(CACHE, "w", encoding="utf8"))
                print(f"  {i}/{len(todo)}", flush=True)
    except KeyboardInterrupt:
        pass
    json.dump(cache, open(CACHE, "w", encoding="utf8"))

    def score(seg):
        p = cache.get(seg, {}).get("plays", 0)
        return round(max(0, min(100, (math.log10(p) - 5) / 4 * 100))) if p > 0 else 0

    out = {}
    for n in names:
        g = max([score(s) for s in segments(n)] or [0])
        if g > 0:
            out[n] = g
    with open(os.path.join(ROOT, "legends.js"), "w", encoding="utf8") as f:
        f.write("/* GENERATED by tools/build_legends.py - do not edit by hand.\n * act name -> legend score 0-100 (Spotify play counts on a log scale, see the script); acts without a score are absent */\n")
        f.write("const LEGENDS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + ";\n")
    print(len(out), "acts with a legend score")
    for n, g in sorted(out.items(), key=lambda x: -x[1])[:40]:
        print(g, n)


if __name__ == "__main__":
    main()
